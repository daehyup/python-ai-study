# 변수의 선언
var = 42
# print("정수 변수:", var)

print(var+10)
print(var-5)
print(var/10)
print(var//10)
print(var%10)

var2 = var / 10
print(var2 > var)

var_float = 3.14
print(var_float * 2)
print(var_float ** 2)

result = var * 10 + 5
print(result)
result = 5 + var * 10
print(result)
result = (5 + var) * 10
print(result)

is_true = True
print(is_true)
is_false = False
print(is_false)

print(is_true and is_false)
print(is_true or is_false)
print(not is_true)